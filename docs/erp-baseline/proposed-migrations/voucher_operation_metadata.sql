CREATE TABLE voucher_operation_requests (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 company_id BIGINT NOT NULL,
 branch_id BIGINT UNSIGNED NOT NULL,
 operation VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 request_key VARBINARY(90) NOT NULL,
 request_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 hash_version SMALLINT UNSIGNED NOT NULL DEFAULT 1,
 voucher_id BIGINT NOT NULL,
 journal_entry_id BIGINT UNSIGNED NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 actor_name VARCHAR(255) NOT NULL,
 completed_at DATETIME(6) NOT NULL,
 UNIQUE KEY uq_vor_request (company_id,operation,request_key),
 UNIQUE KEY uq_vor_voucher (company_id,voucher_id),
 KEY ix_vor_branch (company_id,branch_id,completed_at),
 FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE RESTRICT,
 FOREIGN KEY (branch_id) REFERENCES branches(id) ON DELETE RESTRICT,
 FOREIGN KEY (voucher_id) REFERENCES vouchers(id) ON DELETE RESTRICT,
 FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id) ON DELETE RESTRICT,
 FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE RESTRICT,
 CHECK (operation IN ('CREATE_RECEIPT','CREATE_PAYMENT')),
 CHECK (OCTET_LENGTH(request_key) BETWEEN 1 AND 90),
 CHECK (hash_version=1),
 CHECK (request_hash REGEXP '^[0-9a-f]{64}$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

