 CONSTRAINT fk_ias_sale FOREIGN KEY (sales_invoice_id) REFERENCES sales_invoices(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ias_purchase FOREIGN KEY (purchase_invoice_id) REFERENCES purchase_invoices(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ias_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ias_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ias_journal FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ias_account FOREIGN KEY (party_account_id) REFERENCES accounts(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ias_approver FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT ck_ias_kind CHECK (
  (invoice_type='SALE' AND sales_invoice_id IS NOT NULL AND customer_id IS NOT NULL AND purchase_invoice_id IS NULL AND supplier_id IS NULL)
  OR (invoice_type='PURCHASE' AND purchase_invoice_id IS NOT NULL AND supplier_id IS NOT NULL AND sales_invoice_id IS NULL AND customer_id IS NULL)),
 CONSTRAINT ck_ias_rate CHECK (exchange_rate>0),
 CONSTRAINT ck_ias_totals CHECK (foreign_total>=0 AND base_total>=0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE invoice_line_accounting_snapshots (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 company_id BIGINT NOT NULL,
 snapshot_id BIGINT UNSIGNED NOT NULL,
 sales_invoice_line_id BIGINT UNSIGNED NULL,
 purchase_invoice_line_id BIGINT UNSIGNED NULL,
 item_id BIGINT UNSIGNED NOT NULL,
 accounting_role VARCHAR(40) NOT NULL,
 allocation_component VARCHAR(40) NOT NULL DEFAULT 'LINE',
 account_id BIGINT UNSIGNED NOT NULL,
 journal_entry_line_id BIGINT UNSIGNED NULL,
 original_debit DECIMAL(15,3) NOT NULL DEFAULT 0,
 original_credit DECIMAL(15,3) NOT NULL DEFAULT 0,
 original_quantity DECIMAL(18,6) NOT NULL,
 unit_code VARCHAR(20) NOT NULL,
 original_qty_kg DECIMAL(18,3) NOT NULL DEFAULT 0,
 foreign_net_basis DECIMAL(18,3) NOT NULL,
 base_net_basis DECIMAL(18,3) NOT NULL,
 foreign_discount_basis DECIMAL(18,3) NOT NULL,
 base_discount_basis DECIMAL(18,3) NOT NULL,
 foreign_tax_basis DECIMAL(18,3) NOT NULL,
 base_tax_basis DECIMAL(18,3) NOT NULL,
 base_cost_basis DECIMAL(18,6) NOT NULL,
 captured_at DATETIME NOT NULL,
 PRIMARY KEY (id),
 UNIQUE KEY uq_ilas_sale_role (snapshot_id,sales_invoice_line_id,accounting_role,allocation_component),
 UNIQUE KEY uq_ilas_purchase_role (snapshot_id,purchase_invoice_line_id,accounting_role,allocation_component),
 KEY idx_ilas_scope (company_id,snapshot_id),
 CONSTRAINT fk_ilas_snapshot FOREIGN KEY (company_id,snapshot_id) REFERENCES invoice_accounting_snapshots(company_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ilas_sale_line FOREIGN KEY (sales_invoice_line_id) REFERENCES sales_invoice_lines(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ilas_purchase_line FOREIGN KEY (purchase_invoice_line_id) REFERENCES purchase_invoice_lines(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ilas_item FOREIGN KEY (item_id) REFERENCES items(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ilas_account FOREIGN KEY (account_id) REFERENCES accounts(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_ilas_journal_line FOREIGN KEY (journal_entry_line_id) REFERENCES journal_entry_lines(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT ck_ilas_line CHECK ((sales_invoice_line_id IS NOT NULL AND purchase_invoice_line_id IS NULL) OR (purchase_invoice_line_id IS NOT NULL AND sales_invoice_line_id IS NULL)),
 CONSTRAINT ck_ilas_quantity CHECK (original_quantity>0 AND original_qty_kg>=0),
 CONSTRAINT ck_ilas_sides CHECK (original_debit>=0 AND original_credit>=0 AND (original_debit=0 OR original_credit=0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE voucher_invoice_allocations (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 company_id BIGINT NOT NULL,
 branch_id BIGINT UNSIGNED NULL,
 voucher_id BIGINT NOT NULL,
 snapshot_id BIGINT UNSIGNED NOT NULL,
 journal_entry_id BIGINT UNSIGNED NOT NULL,
 entry_kind VARCHAR(10) NOT NULL,
 reverses_allocation_id BIGINT UNSIGNED NULL,
 currency_code VARCHAR(10) NOT NULL,
 exchange_rate DECIMAL(24,10) NOT NULL,
 foreign_amount DECIMAL(18,3) NOT NULL,
 base_amount DECIMAL(18,3) NOT NULL,
 idempotency_key VARCHAR(100) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 created_by BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL,
 PRIMARY KEY (id),
 UNIQUE KEY uq_via_company_id (company_id,id),
 UNIQUE KEY uq_via_request (company_id,idempotency_key,snapshot_id),
 UNIQUE KEY uq_via_document (company_id,voucher_id,snapshot_id,entry_kind),
 UNIQUE KEY uq_via_reversal (company_id,reverses_allocation_id),
 KEY idx_via_snapshot (company_id,snapshot_id,entry_kind),
 CONSTRAINT fk_via_company FOREIGN KEY (company_id) REFERENCES companies(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_via_branch FOREIGN KEY (branch_id) REFERENCES branches(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_via_voucher FOREIGN KEY (voucher_id) REFERENCES vouchers(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_via_snapshot FOREIGN KEY (company_id,snapshot_id) REFERENCES invoice_accounting_snapshots(company_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_via_journal FOREIGN KEY (journal_entry_id) REFERENCES journal_entries(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_via_reversal FOREIGN KEY (company_id,reverses_allocation_id) REFERENCES voucher_invoice_allocations(company_id,id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT fk_via_creator FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CONSTRAINT ck_via_kind CHECK ((entry_kind='ALLOCATE' AND reverses_allocation_id IS NULL) OR (entry_kind='REVERSE' AND reverses_allocation_id IS NOT NULL)),
 CONSTRAINT ck_via_amounts CHECK (base_amount>0 AND foreign_amount>0 AND exchange_rate>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
